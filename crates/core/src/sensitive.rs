//! Sensitive-content markers: formats that password managers add to a copy so that clipboard
//! tools leave it alone. Content offered with any of them is never synced.

/// Every marker, matched exactly (case-sensitive) against the offered format names.
///
/// The two Windows flag formats hold a DWORD and mark the content as sensitive only when it is 0.
/// Their name alone says nothing, so the Windows backend reads the value and reports them as
/// `<name>=<value>` in decimal (e.g. `CanUploadToCloudClipboard=0`) before calling
/// [`sensitive_marker`].
const MARKERS: [&str; 8] = [
    // Windows.
    "ExcludeClipboardContentFromMonitorProcessing",
    "CanUploadToCloudClipboard=0",
    "CanIncludeInClipboardHistory=0",
    // Linux. KeePassXC offers it with the value `secret`; no app offers it to say "not secret",
    // so its presence is enough and the value is never read.
    "x-kde-passwordManagerHint",
    // macOS (nspasteboard.org conventions, plus 1Password's legacy type).
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
];

/// Windows formats that hold a DWORD flag, reported as `<name>=<value>` (see [`MARKERS`]).
pub const WINDOWS_FLAG_FORMATS: [&str; 2] =
    ["CanUploadToCloudClipboard", "CanIncludeInClipboardHistory"];

/// The first sensitive-content marker among `formats` (native format names, as in
/// `ClipboardChange::formats`), or `None` if the content can be synced.
#[must_use]
pub fn sensitive_marker<S: AsRef<str>>(formats: &[S]) -> Option<&'static str> {
    MARKERS
        .into_iter()
        .find(|marker| formats.iter().any(|format| format.as_ref() == *marker))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A plain text copy plus `marker`, as each platform names its text format.
    fn copy_with(marker: &str) -> [&str; 4] {
        [
            "text/plain;charset=utf-8",
            "public.utf8-plain-text",
            "CF_UNICODETEXT",
            marker,
        ]
    }

    #[test]
    fn windows_exclusion_marker_by_presence() {
        let marker = "ExcludeClipboardContentFromMonitorProcessing";
        assert_eq!(sensitive_marker(&copy_with(marker)), Some(marker));
    }

    #[test]
    fn windows_flags_only_when_zero() {
        for flag in WINDOWS_FLAG_FORMATS {
            let zero = format!("{flag}=0");
            assert_eq!(
                sensitive_marker(&copy_with(&zero)),
                Some(zero.as_str()),
                "{flag}"
            );
            assert_eq!(sensitive_marker(&copy_with(&format!("{flag}=1"))), None);
            // The bare name (value not read) is not a marker by itself.
            assert_eq!(sensitive_marker(&copy_with(flag)), None);
        }
    }

    #[test]
    fn kde_password_manager_hint() {
        let marker = "x-kde-passwordManagerHint";
        assert_eq!(sensitive_marker(&copy_with(marker)), Some(marker));
    }

    #[test]
    fn macos_markers() {
        for marker in [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
            "com.agilebits.onepassword",
        ] {
            assert_eq!(sensitive_marker(&copy_with(marker)), Some(marker));
        }
    }

    #[test]
    fn plain_copies_are_not_sensitive() {
        assert_eq!(sensitive_marker(&copy_with("image/png")), None);
        assert_eq!(sensitive_marker::<&str>(&[]), None);
    }

    #[test]
    fn matches_exactly() {
        for near_miss in [
            "x-kde-passwordmanagerhint",
            "x-kde-passwordManagerHint ",
            "org.nspasteboard.ConcealedType.extra",
            "CanUploadToCloudClipboard=00",
        ] {
            assert_eq!(sensitive_marker(&copy_with(near_miss)), None, "{near_miss}");
        }
    }
}
